#!/usr/bin/env python3
"""Generate ``web/src/app/tokens.css`` from the Python design tokens.

Accepts:
    --check: Compare with the committed stylesheet instead of writing it.

Returns:
    None. Writes one stylesheet holding both palettes and the Tailwind mapping.

Notes:
    Light values live in ``:root`` and dark values in ``.dark``, and both blocks
    declare exactly the same names. That parity is asserted here, so a token
    added to one palette cannot silently go missing from the other. Tailwind v4
    utilities are generated from ``@theme inline``, which makes every utility
    resolve through the same ``--aa-*`` variables and switch with the class.
"""

import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "frontend" / "styles" / "tokens.py"
OUTPUT = ROOT / "web" / "src" / "app" / "tokens.css"

BANNER = (
    "/* Generated by scripts/gen_tokens.py from frontend/styles/tokens.py. */\n"
    "/* Do not edit by hand: change the tokens module and run make gen-tokens. */\n"
)


def _load():
    """Load the token module from its path without importing the frontend package.

    Returns:
        module: The imported design-token module.
    """
    spec = importlib.util.spec_from_file_location("aa_design_tokens", SOURCE)
    if spec is None or spec.loader is None:
        raise SystemExit("cannot load " + str(SOURCE))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _rule(selector: str, theme: str, module) -> str:
    """Render one palette as a CSS custom property rule.

    Args:
        selector (str): Rule selector, for example ``:root`` or ``.dark``.
        theme (str): Palette name, ``light`` or ``dark``.
        module: Loaded token module.

    Returns:
        str: A rule declaring every palette, radius, motion, and font token.
    """
    lines = [selector + " {", "  color-scheme: " + theme + ";"]
    for name, value in module.palette(theme).items():
        lines.append("  --" + name + ": " + value + ";")
    for group in (module.RADII, module.MOTION, module.FONTS):
        for name, value in group.items():
            lines.append("  --" + name + ": " + value + ";")
    lines.append("}")
    return "\n".join(lines)


def _theme(module) -> str:
    """Render the Tailwind v4 theme mapping for the semantic tokens.

    Args:
        module: Loaded token module.

    Returns:
        str: An ``@theme inline`` block exposing colors, radii, shadows, and fonts.
    """
    names = sorted(name for name in module.DARK if name.startswith("aa-"))
    lines = ["@theme inline {"]
    for name in names:
        lines.append("  --color-" + name[3:] + ": var(--" + name + ");")
    for name in module.RADII:
        suffix = name[len("aa-radius-"):] if name.startswith("aa-radius-") else "default"
        lines.append("  --radius-" + suffix + ": var(--" + name + ");")
    for number in ("1", "2", "3"):
        lines.append("  --shadow-" + number + ": var(--aa-shadow-" + number + ");")
    for name in module.FONTS:
        lines.append("  --font-" + name[len("aa-font-"):] + ": var(--" + name + ");")
    lines.append("}")
    return "\n".join(lines)


def build() -> str:
    """Render the complete stylesheet used by the Next.js app.

    Returns:
        str: Banner, both palette blocks, and the Tailwind theme mapping.

    Raises:
        SystemExit: If the palettes or the default theme disagree.
    """
    module = _load()
    dark_names = set(module.palette("dark"))
    light_names = set(module.palette("light"))
    if dark_names != light_names:
        raise SystemExit("palette drift: " + ", ".join(sorted(dark_names ^ light_names)))
    if module.DEFAULT_THEME != "dark":
        raise SystemExit("the web app ships the dark palette by default")
    return "\n\n".join([
        BANNER + _rule(":root", "light", module),
        _rule(".dark", "dark", module),
        _theme(module),
    ]) + "\n"


def main(argv: list[str]) -> int:
    """Write the stylesheet, or verify it with ``--check``.

    Args:
        argv (list[str]): Command line arguments.

    Returns:
        int: Process exit code, non-zero when ``--check`` finds drift.
    """
    css = build()
    if "--check" in argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != css:
            print("out of date: " + str(OUTPUT.relative_to(ROOT)))
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(css, encoding="utf-8")
    print("wrote " + str(OUTPUT.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
