#!/usr/bin/env python3
"""Generate the OpenAPI snapshot and TypeScript request types for the web app.

Accepts:
    --check: Regenerate in memory and compare with the committed files instead of
        writing them. Exits non-zero when either file is out of date.

Returns:
    None. Writes ``web/openapi.json`` and ``web/src/types/api.generated.ts``.

Notes:
    Only request models are emitted. The FastAPI routes return ``dict`` and
    ``list[dict]`` without ``response_model``, so those operations carry no
    response schema. Adding ``response_model`` retroactively would make FastAPI
    silently drop undeclared fields, so response types stay hand-written in
    ``web/src/types/api.ts`` and are guarded by ``tests/test_api_contract.py``.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OPENAPI_PATH = ROOT / "web" / "openapi.json"
TYPES_PATH = ROOT / "web" / "src" / "types" / "api.generated.ts"

HEADER = """/**
 * Generated by scripts/gen_types.py from the FastAPI OpenAPI schema.
 * Do not edit this file by hand; run `make gen-types` instead.
 *
 * These are request-body models. Response shapes are documented in
 * `web/src/types/api.ts` because the backend returns plain dictionaries.
 */

"""


def _is_identifier(name: str) -> bool:
    """Return whether a JSON property name is a bare TypeScript identifier.

    Args:
        name (str): Property name from the JSON schema.

    Returns:
        bool: True when the name needs no quoting.
    """
    if not name:
        return False
    if not (name[0].isalpha() or name[0] in "_$"):
        return False
    return all(char.isalnum() or char in "_$" for char in name[1:])


def _literal(value) -> str:
    """Render one JSON schema enum value as a TypeScript literal.

    Args:
        value: Enum or const member from the schema.

    Returns:
        str: A valid TypeScript literal union member.
    """
    return json.dumps(value, ensure_ascii=False)


def _ts_type(schema) -> str:
    """Convert one JSON schema fragment into a TypeScript type expression.

    Args:
        schema (dict | bool | None): Schema fragment. ``True`` accepts any value.

    Returns:
        str: TypeScript type covering objects, arrays, unions, enums, and refs.
    """
    if schema is None or schema is True:
        return "unknown"
    if not isinstance(schema, dict):
        return "unknown"

    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]

    if isinstance(schema.get("enum"), list):
        return " | ".join(_literal(item) for item in schema["enum"])

    if "const" in schema:
        return _literal(schema["const"])

    if "anyOf" in schema or "oneOf" in schema:
        members = schema.get("anyOf") or schema.get("oneOf") or []
        parts: list[str] = []
        nullable = False
        for member in members:
            if isinstance(member, dict) and member.get("type") == "null":
                nullable = True
                continue
            rendered = _ts_type(member)
            if rendered not in parts:
                parts.append(rendered)
        joined = " | ".join(parts) or "null"
        if nullable and parts:
            return f"{joined} | null"
        return joined

    kind = schema.get("type")

    if kind == "array":
        items = _ts_type(schema.get("items"))
        if " | " in items and not items.startswith("("):
            return f"({items})[]"
        return f"{items}[]"

    if kind == "object" or "properties" in schema:
        properties = schema.get("properties") or {}
        if not properties:
            additional = schema.get("additionalProperties")
            if isinstance(additional, dict):
                return f"Record<string, {_ts_type(additional)}>"
            return "Record<string, unknown>"
        required = set(schema.get("required") or [])
        fields = []
        for name, value in properties.items():
            key = name if _is_identifier(name) else _literal(name)
            optional = "" if name in required else "?"
            fields.append(f"{key}{optional}: {_ts_type(value)};")
        return "{ " + " ".join(fields) + " }"

    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    return "unknown"


def _render(name: str, schema: dict) -> str:
    """Render one named request schema as an exported TypeScript declaration.

    Args:
        name (str): Component schema name.
        schema (dict): JSON schema for that component.

    Returns:
        str: ``interface`` declaration, or a ``type`` alias for free-form maps.
    """
    title = str(schema.get("title") or name)
    description = str(schema.get("description") or "").strip()
    lines: list[str] = []
    if description:
        summary = " ".join(description.split())
        lines.append("/** " + summary.replace("*/", "*") + " */")

    properties = schema.get("properties") or {}
    required = set(schema.get("required") or [])

    if not properties:
        additional = schema.get("additionalProperties")
        target = f"Record<string, {_ts_type(additional)}>" if isinstance(additional, dict) else "Record<string, unknown>"
        lines.append(f"export type {title} = {target};")
        return "\n".join(lines)

    lines.append(f"export interface {title} {{")
    for prop, prop_schema in properties.items():
        key = prop if _is_identifier(prop) else _literal(prop)
        optional = "" if prop in required else "?"
        lines.append(f"  {key}{optional}: {_ts_type(prop_schema)};")
    lines.append("}")
    return "\n".join(lines)


def build() -> tuple[str, str]:
    """Import the app and render the OpenAPI document plus the type module.

    Returns:
        tuple[str, str]: Serialized OpenAPI JSON and TypeScript source.

    Raises:
        ImportError: If the backend module cannot be imported.
    """
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))

    from app.main import app  # Imported lazily so --check still needs the app.

    document = app.openapi()
    snapshot = json.dumps(document, indent=2, ensure_ascii=False) + "\n"

    schemas = (document.get("components") or {}).get("schemas") or {}
    blocks = [
        _render(name, schema)
        for name, schema in sorted(schemas.items())
        if isinstance(schema, dict)
    ]
    return snapshot, HEADER + "\n\n".join(blocks) + "\n"


def main(argv: list[str]) -> int:
    """Write generated files, or verify them with ``--check``.

    Args:
        argv (list[str]): Command line arguments.

    Returns:
        int: Process exit code, non-zero when ``--check`` finds drift.
    """
    check = "--check" in argv
    snapshot, types = build()
    outputs = ((OPENAPI_PATH, snapshot), (TYPES_PATH, types))

    if check:
        stale = [
            path for path, content in outputs
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        for path in stale:
            print("out of date: " + str(path.relative_to(ROOT)))
        return 1 if stale else 0

    for path, content in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print("wrote " + str(path.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))


