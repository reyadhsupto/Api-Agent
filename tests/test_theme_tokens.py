"""Guards for the shared design tokens consumed by the Next.js UI."""

import pathlib
import re

from design import tokens

WEB_APP = pathlib.Path(__file__).resolve().parent.parent / "web" / "src" / "app"
CJK = re.compile(r"[\u2e80-\u9fff\uac00-\ud7af\uff00-\uffef]")


def _web_tokens_css() -> str:
    """Return the generated stylesheet consumed by the Next.js app."""
    path = WEB_APP / "tokens.css"
    return path.read_text(encoding="utf-8") if path.exists() else ""


def _declared_keys(selector: str) -> set[str]:
    """Return custom property names declared by one stylesheet selector."""
    match = re.search(re.escape(selector) + r"\s*\{(.*?)\n\}", _web_tokens_css(), re.DOTALL)
    if not match:
        return set()
    return set(re.findall(r"--([a-z0-9-]+)\s*:", match.group(1)))


def test_palettes_declare_the_same_tokens():
    """Both palettes must expose identical token names."""
    assert set(tokens.DARK) == set(tokens.LIGHT)


def test_box_tokens_exist_in_both_palettes():
    """The component system depends on these surface and edge tokens."""
    required = {
        "aa-canvas", "aa-rail", "aa-panel", "aa-panel-alt", "aa-elevated",
        "aa-overlay", "aa-hover", "aa-active", "aa-line", "aa-line-soft",
        "aa-line-strong", "aa-line-contrast", "aa-line-accent", "aa-text",
        "aa-text-dim", "aa-text-mute", "aa-on-accent", "aa-box-fill",
        "aa-box-line", "aa-box-shadow", "aa-box-pad", "aa-chip-fill",
        "aa-chip-line", "aa-accent-soft", "aa-accent-wash",
    }
    for theme in ("dark", "light"):
        assert required <= set(tokens.palette(theme))


def test_dark_canvas_is_pure_black():
    """The dark workspace is black, not a grey surface."""
    assert tokens.DARK["aa-canvas"] == "#000000"


def test_edge_ladder_rises_above_black():
    """Dark borders rise in contrast to remain visible on the canvas."""
    ladder = {"aa-line-soft": 0.14, "aa-line": 0.20,
              "aa-line-strong": 0.30, "aa-line-contrast": 0.40}
    for name, floor in ladder.items():
        alpha = float(tokens.DARK[name].split(",")[-1].strip(" )"))
        assert alpha >= floor, (name, alpha, floor)


def test_accent_ink_is_not_white():
    """White on the orange accent measures 2.8:1 and must not be used."""
    for theme in ("dark", "light"):
        assert tokens.palette(theme)["aa-on-accent"].lower() not in {"#fff", "#ffffff"}


def test_every_var_reference_resolves():
    """The generated stylesheet uses only variables declared by the token source."""
    defined = set(tokens.palette("dark")) | set(tokens.RADII) | set(tokens.MOTION) | set(tokens.FONTS)
    missing = [
        reference for reference in re.findall(r"var\(--(aa-[a-z0-9-]+)", _web_tokens_css())
        if reference not in defined
    ]
    assert not missing, missing


def test_default_theme_is_dark():
    """The shipped default is the pure black workspace."""
    assert tokens.DEFAULT_THEME == "dark"


def test_web_tokens_are_generated():
    """The Next.js app consumes the stylesheet emitted by the token generator."""
    css = _web_tokens_css()
    assert "Generated by scripts/gen_tokens.py" in css
    assert "@theme inline" in css


def test_web_token_blocks_declare_identical_keys():
    """A token added to one palette must be added to the other."""
    light = _declared_keys(":root")
    dark = _declared_keys(".dark")
    assert light, "no :root tokens found"
    assert dark, "no .dark tokens found"
    assert light == dark, sorted(light ^ dark)


def test_web_tokens_include_the_box_system():
    """Cards, chips, edges, radii, and fonts survive the token build."""
    light = _declared_keys(":root")
    required = {
        "aa-canvas", "aa-rail", "aa-panel", "aa-panel-alt", "aa-elevated",
        "aa-overlay", "aa-hover", "aa-active", "aa-line-soft", "aa-line",
        "aa-line-strong", "aa-line-contrast", "aa-line-accent", "aa-text",
        "aa-text-dim", "aa-text-mute", "aa-on-accent", "aa-box-fill",
        "aa-box-line", "aa-box-shadow", "aa-box-pad", "aa-chip-fill",
        "aa-chip-line", "aa-accent-soft", "aa-accent-wash", "aa-shadow-1",
        "aa-shadow-2", "aa-shadow-3", "aa-radius-xs", "aa-radius-sm",
        "aa-radius-md", "aa-radius", "aa-radius-lg", "aa-radius-pill",
        "aa-font-ui", "aa-font-mono",
    }
    assert required <= light, sorted(required - light)


def test_web_theme_mapping_exposes_semantic_utilities():
    """Tailwind utilities resolve through shared CSS custom properties."""
    css = _web_tokens_css()
    for utility in ("--color-canvas", "--color-panel", "--color-line",
                    "--color-text", "--color-accent", "--color-on-accent",
                    "--radius-default", "--radius-lg", "--shadow-1"):
        assert utility in css, utility


def test_web_tokens_are_ascii_and_balanced():
    """Generated stylesheets remain balanced and contain no stray glyphs."""
    css = _web_tokens_css()
    assert css
    assert css.count("{") == css.count("}")
    assert not CJK.search(css)
    assert all(ord(char) < 128 for char in css), "non-ascii in tokens.css"
